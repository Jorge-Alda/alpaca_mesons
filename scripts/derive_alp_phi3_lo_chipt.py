"""Derive the one-ALP, three-pseudoscalar terms of the LO chiPT Lagrangian.

Invocation:
    .venv/bin/python scripts/derive_alp_phi3_lo_chipt.py

Conventions follow Appendix A of Alda:2026bar. All fields and decay constants
are in natural units. The bookkeeping symbols count ALP and Phi powers and are
removed after coefficient extraction.
"""

import sympy as sp


def show(label: str, expression: sp.Expr) -> None:
    print(f"{label}:\n{sp.latex(expression)}\n")


n = sp.Symbol("N_f", integer=True, positive=True)
f_pi, f_a, B_0 = sp.symbols("f_pi f_a B_0", positive=True)
rho, epsilon = sp.symbols("rho epsilon")
a, da = sp.symbols("a partial_a")

Phi = sp.MatrixSymbol("Phi", n, n)
dPhi = sp.MatrixSymbol("partial_Phi", n, n)
cA = sp.MatrixSymbol("c_q^A", n, n)
cV = sp.MatrixSymbol("c_q^V", n, n)
cP = sp.MatrixSymbol("c_q^P", n, n)
mq = sp.MatrixSymbol("m_q", n, n)


def commutator_map(argument: sp.MatrixExpr, field: sp.MatrixExpr) -> sp.MatrixExpr:
    """Appendix convention C_field[argument] = [argument, field]."""
    return argument * field - field * argument


def anticommutator_map(argument: sp.MatrixExpr, field: sp.MatrixExpr) -> sp.MatrixExpr:
    """Appendix convention A_field[argument] = {argument, field}."""
    return argument * field + field * argument


def power(linear_map, argument: sp.MatrixExpr, field: sp.MatrixExpr, order: int):
    result = argument
    for _ in range(order):
        result = linear_map(result, field)
    return result


def scalar_coefficient(expression, symbol: sp.Symbol, order: int):
    """Extract a scalar-series coefficient from an abstract MatrixExpr."""
    derivative = expression
    for _ in range(order):
        derivative = sp.diff(derivative, symbol)
    return derivative.subs(symbol, 0) / sp.factorial(order)


phi = rho * Phi / (2 * f_pi)
dphi = rho * dPhi / (2 * f_pi)

# Appendix A.13 series, retaining all orders that can contribute to a Phi^3.
u_meson = -2 * (dphi - power(commutator_map, dphi, phi, 2) / sp.factorial(3))
u_alp_axial = 2 * epsilon * da / f_a * (
    cA - power(commutator_map, cA, phi, 2) / sp.factorial(2)
)
u_alp_vector = -2 * sp.I * epsilon * da / f_a * (
    power(commutator_map, cV, phi, 1)
    - power(commutator_map, cV, phi, 3) / sp.factorial(3)
)

kinetic_matrix = sp.expand(
    f_pi**2 / 4
    * (
        u_meson * (u_alp_axial + u_alp_vector)
        + (u_alp_axial + u_alp_vector) * u_meson
    )
)
kinetic_a_phi3_matrix = scalar_coefficient(
    scalar_coefficient(kinetic_matrix, epsilon, 1), rho, 3
)
kinetic_a_phi3_raw = sp.Trace(kinetic_a_phi3_matrix)

# Cyclicity gives Tr(X C_phi^2[Y]) = Tr(C_phi^2[X] Y). Applying it to
# the two cross terms combines their coefficients as 1 + 1/3 = 4/3.
kinetic_a_phi3 = da / (6 * f_a * f_pi) * sp.Trace(
    cA * power(commutator_map, dPhi, Phi, 2)
)

# chi_P is already linear in the ALP. The cubic term follows from the
# -A_phi^3/3 term in 2 sin(A_phi)[chi_P].
chi_P = 2 * B_0 * epsilon * a / f_a * anticommutator_map(cP, mq)
chi_plus_odd = 2 * (
    power(anticommutator_map, chi_P, phi, 1)
    - power(anticommutator_map, chi_P, phi, 3) / sp.factorial(3)
)
breaking = sp.expand(f_pi**2 * chi_plus_odd / 4)
breaking_a_phi3_matrix = scalar_coefficient(
    scalar_coefficient(breaking, epsilon, 1), rho, 3
)
breaking_a_phi3_nested = sp.Trace(breaking_a_phi3_matrix)

# Repeated trace cyclicity gives Tr(A_Phi^3[X]) = 8 Tr(Phi^3 X).
breaking_a_phi3 = -B_0 * a / (6 * f_a * f_pi) * sp.Trace(
    Phi**3 * anticommutator_map(cP, mq)
)

show("Dimensionless field", Phi / (2 * f_pi))
show("Mesonic vielbein through Phi^3", u_meson.subs(rho, 1))
show("Axial one-ALP vielbein through Phi^2", u_alp_axial.subs({rho: 1, epsilon: 1}))
show("Vector one-ALP vielbein through Phi^3", u_alp_vector.subs({rho: 1, epsilon: 1}))
show("Raw kinetic coefficient at one ALP and Phi^3", kinetic_a_phi3_raw)
show("Kinetic result after trace cyclicity", kinetic_a_phi3)
show("Raw symmetry-breaking coefficient at one ALP and Phi^3", breaking_a_phi3_nested)
show("Symmetry-breaking result after trace cyclicity", breaking_a_phi3)

# Diagnostics on the scalar coefficients generated by the series.
assert sp.simplify(sp.Rational(1, 1) + sp.Rational(1, 3) - sp.Rational(4, 3)) == 0
assert sp.simplify(
    -f_pi**2 / 12 * (2 * B_0 / f_a) / (2 * f_pi) ** 3
    + B_0 / (48 * f_a * f_pi)
) == 0

# Deterministic matrix diagnostics verify the trace reductions without imposing
# commutativity on the abstract derivation above.
Phi_test = sp.Matrix([[1, 2], [3, 5]])
dPhi_test = sp.Matrix([[7, 11], [13, 17]])
cA_test = sp.Matrix([[19, 23], [29, 31]])
cP_test = sp.Matrix([[37, 41], [43, 47]])
mq_test = sp.Matrix([[53, 0], [0, 59]])

kinetic_raw_test = kinetic_a_phi3_raw.doit().subs(
    {Phi: Phi_test, dPhi: dPhi_test, cA: cA_test}
)
kinetic_reduced_test = kinetic_a_phi3.doit().subs(
    {Phi: Phi_test, dPhi: dPhi_test, cA: cA_test}
)
breaking_raw_test = breaking_a_phi3_nested.doit().subs(
    {Phi: Phi_test, cP: cP_test, mq: mq_test}
)
breaking_reduced_test = breaking_a_phi3.doit().subs(
    {Phi: Phi_test, cP: cP_test, mq: mq_test}
)

assert sp.simplify(kinetic_raw_test - kinetic_reduced_test) == 0
assert sp.simplify(breaking_raw_test - breaking_reduced_test) == 0
